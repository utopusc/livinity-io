// ─── Public API ──────────────────────────────────────────────────────────

/**
 * Materialise (or overwrite) the per-surface CLAUDE.md for an installed app.
 *
 * Idempotent: re-running with the same args overwrites the same path. The
 * file body itself includes a `Generated by … at <ISO>` footer comment so
 * the mtime advances on every call.
 *
 * Non-fatal: NEVER throws. All errors collapse to
 * `{status: 'failed-non-fatal', reason}` so the caller can keep going.
 */
export async function writeSurfaceContext(
	opts: WriteSurfaceContextOptions,
): Promise<WriteSurfaceContextResult> {
	const logger = opts.logger ?? NOOP_LOGGER
	const vaultPath = opts.vaultPath ?? DEFAULT_VAULT_PATH
	const ownerUser = opts.ownerUser ?? DEFAULT_OWNER_USER
	const ownerGroup = opts.ownerGroup ?? DEFAULT_OWNER_GROUP
	const surfaceDir = path.join(vaultPath, 'surfaces', opts.kind, opts.metadata.appId)
	const claudeMdPath = path.join(surfaceDir, 'CLAUDE.md')
	try {
		await mkdir(surfaceDir, {recursive: true, mode: 0o755})
		const body =
			opts.kind === 'webapp'
				? renderWebappTemplate(opts.metadata)
				: renderNativeTemplate(opts.metadata)
		await writeFile(claudeMdPath, body, {encoding: 'utf8', mode: 0o644})
		// Explicit chmod — writeFile's `mode` option only applies on file
		// creation, not on overwrite. The chmod here guarantees the file
		// is 0644 even on the idempotent re-write path.
		await chmod(claudeMdPath, 0o644)
		// Best-effort chown. The scaffolder runs as livinityd's uid which is
		// either root (Mini PC systemd) or a non-privileged dev user (CI).
		// On a non-root or non-Linux box this will throw; we log + continue.
		try {
			await execFileAsync('chown', ['-R', `${ownerUser}:${ownerGroup}`, surfaceDir])
		} catch (err) {
			logger.error(
				`writeSurfaceContext: chown ${surfaceDir} failed (continuing)`,
				err,
			)
		}
		logger.log(
			`writeSurfaceContext: wrote ${claudeMdPath} (kind=${opts.kind} appId=${opts.metadata.appId})`,
		)
		return {status: 'written', path: claudeMdPath}
	} catch (err) {
		logger.error(
			`writeSurfaceContext: failed for kind=${opts.kind} appId=${opts.metadata.appId}`,
			err,
		)
		return {
			status: 'failed-non-fatal',
			reason: err instanceof Error ? err.message : String(err),
		}
	}
}

/**
 * Move-to-trash the per-surface dir on uninstall.
 *
 * Renames `vault/surfaces/<kind>/<appId>` → `<dir>.deleted-<unixMs>`.
 * This is deliberately a rename (NOT an unlink) so the operator can
 * recover the directory if the uninstall was accidental.
 *
 * Non-fatal: NEVER throws. Missing dir → `{status: 'absent'}`. Any other
 * failure → `{status: 'failed-non-fatal', reason}`.
 */
export async function removeSurfaceContext(
	opts: RemoveSurfaceContextOptions,
): Promise<RemoveSurfaceContextResult> {
	const logger = opts.logger ?? NOOP_LOGGER
	const vaultPath = opts.vaultPath ?? DEFAULT_VAULT_PATH
	const surfaceDir = path.join(vaultPath, 'surfaces', opts.kind, opts.appId)
	try {
		const s = await stat(surfaceDir).catch(() => null)
		if (!s || !s.isDirectory()) {
			logger.log(`removeSurfaceContext: ${surfaceDir} absent, no-op`)
			return {status: 'absent'}
		}
		const trashed = `${surfaceDir}.deleted-${Date.now()}`
		await rename(surfaceDir, trashed)
		logger.log(`removeSurfaceContext: renamed ${surfaceDir} -> ${trashed}`)
		return {status: 'renamed', from: surfaceDir, to: trashed}
	} catch (err) {
		logger.error(
			`removeSurfaceContext: failed for kind=${opts.kind} appId=${opts.appId}`,
			err,
		)
		return {
			status: 'failed-non-fatal',
			reason: err instanceof Error ? err.message : String(err),
		}
	}
}
