// Phase 163-01 — Surface vault context scaffolder (master plan D-V34-C).
//
// Materialises per-app `CLAUDE.md` context files into the LivOS vault at
// /home/bruce/livinity-vault/surfaces/<kind>/<appId>/CLAUDE.md when an app
// is installed, and renames the surface dir to `.deleted-<unixMs>` (move-
// to-trash, deliberately NOT an unlink) when uninstalled.
//
// Both writeSurfaceContext and removeSurfaceContext are NON-FATAL: all
// recoverable errors are reflected in the discriminated-union result;
// the caller (apps.ts::installForUser, native-installer.ts::install)
// must never have its install path fail because a vault write failed
// (vault may be unmounted, permissions wrong, disk full, etc).
//
// Permission model: 0755 dirs / 0644 files / chown -R bruce:bruce.
// chown is best-effort — its failure is logged but never propagated.
//
// Phase 163-02 (next plan) reads these dirs as `cwd` for surface-prefixed
// sessions (`webapp:` / `native:`). Without 163-01 there is nothing to
// point cwd at.

import {mkdir, writeFile, chmod, stat, rename} from 'node:fs/promises'
import {execFile} from 'node:child_process'
import {promisify} from 'node:util'
import path from 'node:path'

const execFileAsync = promisify(execFile)

const NOOP_LOGGER = {log: () => {}, error: () => {}}
const DEFAULT_VAULT_PATH = '/home/bruce/livinity-vault'
const DEFAULT_OWNER_USER = 'bruce'
const DEFAULT_OWNER_GROUP = 'bruce'

// ─── Public types ────────────────────────────────────────────────────────

export type SurfaceKind = 'webapp' | 'native'

export interface SurfaceMetadata {
	appId: string // e.g. 'suna', 'blender'
	name: string // human-readable display name
	description?: string
	category?: string
	subdomain?: string // webapp only — '<appId>-<username>'
	binaryPath?: string // native only — manifest.launch.binaryPath
	appSpecificHint?: string // optional — appended to "Tools Available"
}

export interface WriteSurfaceContextOptions {
	kind: SurfaceKind
	metadata: SurfaceMetadata
	vaultPath?: string // default '/home/bruce/livinity-vault'
	ownerUser?: string // default 'bruce'
	ownerGroup?: string // default 'bruce'
	logger?: {log: (m: string) => void; error: (m: string, err?: unknown) => void}
}

export type WriteSurfaceContextResult =
	| {status: 'written'; path: string}
	| {status: 'failed-non-fatal'; reason: string}

export interface RemoveSurfaceContextOptions {
	kind: SurfaceKind
	appId: string
	vaultPath?: string // default '/home/bruce/livinity-vault'
	logger?: {log: (m: string) => void; error: (m: string, err?: unknown) => void}
}

export type RemoveSurfaceContextResult =
	| {status: 'renamed'; from: string; to: string}
	| {status: 'absent'}
	| {status: 'failed-non-fatal'; reason: string}

// ─── Template renderers (pure — testable, no I/O) ─────────────────────────
//
// The template literal content begins immediately after the opening
// backtick at column 0 of its content — the rendered output must NOT
// have leading whitespace per line. Do NOT reformat or re-indent these
// strings; the runtime invariants (test 6/7) regex-match against the
// flush-left output.

